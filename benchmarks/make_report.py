#!/usr/bin/env python
"""Turn benchmark result folders into the tables of the report and of the paper.

Reads every ``<results>/<dataset>/results.csv`` written by ``run_ibm.py`` / ``run_elliptic.py``
(or ``amlgm benchmark``) and writes

* ``<results>/REPORT.md``       — Markdown tables (mean ± std over seeds), per-motif recall and
                                  the environment of every run;
* ``<results>/results.tex``     — a booktabs table ready to ``\\input`` in ``paper/``.

Nothing is invented: a cell is empty when a model was not run, and ``std`` is shown as blank
for deterministic models (a single run).

    python benchmarks/make_report.py benchmarks/results

Results of the same dataset produced elsewhere (e.g. the GNNs trained on a GPU with notebook
``04``) are merged by giving their folder too; the report is written into the first folder:

    python benchmarks/make_report.py benchmarks/results gpu-results/results
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import pandas as pd

METRICS = [
    ("pr_auc", "PR-AUC"),
    ("f1", "F1"),
    ("precision", "Precision"),
    ("recall", "Recall"),
    ("recall_at_k", "Recall@k"),
]
SYNTHETIC_MARKERS = ("synthetic", "smoke", "demo")


def is_synthetic(name: str) -> bool:
    return any(marker in name.lower() for marker in SYNTHETIC_MARKERS)


def cell(mean: float, std: float, digits: int = 3) -> str:
    if mean is None or (isinstance(mean, float) and math.isnan(mean)):
        return ""
    if std is None or (isinstance(std, float) and math.isnan(std)):
        return f"{mean:.{digits}f}"
    return f"{mean:.{digits}f} ± {std:.{digits}f}"


def summarise(results: pd.DataFrame) -> pd.DataFrame:
    """One row per model with ``mean ± std`` strings (and the raw PR-AUC mean to sort on)."""
    rows = []
    for model, group in results.groupby("model", sort=False):
        row: dict[str, object] = {"model": model, "runs": len(group)}
        for key, label in METRICS:
            if key in group:
                row[label] = cell(group[key].mean(), group[key].std(ddof=1))
        row["_sort"] = group["pr_auc"].mean()
        rows.append(row)
    return pd.DataFrame(rows).sort_values("_sort", ascending=False).drop(columns="_sort")


def to_md(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, frame.columns)) + " |"
    rule = "|" + "|".join("---" for _ in frame.columns) + "|"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, rule, *body])


def to_latex(tables: dict[str, pd.DataFrame]) -> str:
    out = [
        "% Generated by benchmarks/make_report.py — do not edit by hand.",
        "\\begin{tabular}{llrrrrr}",
        "\\toprule",
        "Dataset & Model & PR-AUC & F1 & Precision & Recall & Recall@k \\\\",
        "\\midrule",
    ]
    for dataset, table in tables.items():
        name = dataset.replace("_", "\\_")
        for i, (_, row) in enumerate(table.iterrows()):
            cells = [str(row.get(label, "")).replace("±", "$\\pm$") for _, label in METRICS]
            out.append(
                f"{name if i == 0 else ''} & {row['model']} & " + " & ".join(cells) + " \\\\"
            )
        out.append("\\midrule")
    out[-1] = "\\bottomrule"
    out.append("\\end{tabular}")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument(
        "results",
        type=Path,
        nargs="+",
        help="folder(s) containing one sub-folder per dataset; the report is written into the "
        "first one, runs of the same dataset found in the other folders are merged into it",
    )
    args = parser.parse_args(argv)
    out_dir = args.results[0]

    by_dataset: dict[str, list[Path]] = {}
    for root in args.results:
        if not root.is_dir():
            parser.error(f"{root} is not a folder")
        for path in sorted(p for p in root.iterdir() if (p / "results.csv").exists()):
            by_dataset.setdefault(path.name, []).append(path)
    if not by_dataset:
        parser.error(f"no <dataset>/results.csv found under {', '.join(map(str, args.results))}")

    lines = ["# Benchmark report", ""]
    latex_tables: dict[str, pd.DataFrame] = {}
    for name in sorted(by_dataset):
        folders = by_dataset[name]
        results = pd.concat([pd.read_csv(f / "results.csv") for f in folders], ignore_index=True)
        if {"model", "seed"} <= set(results.columns):
            # a model re-run in a later folder replaces the earlier run of the same seed
            results = results.drop_duplicates(subset=["model", "seed"], keep="last")
        folder = folders[0]
        config_file = next(
            (f / "config.json" for f in folders if (f / "config.json").exists()), None
        )
        config = json.loads(config_file.read_text()) if config_file else {}
        lines += [f"## {folder.name}", ""]
        if len(folders) > 1:
            lines += ["Merged from: " + ", ".join(f"`{f}`" for f in folders) + ".", ""]
        if is_synthetic(folder.name):
            lines += [
                "> **Synthetic stand-in data — validates the pipeline only. Do not quote these "
                "numbers as results on IBM AML or Elliptic.**",
                "",
            ]
        sizes = config.get("split_sizes")
        if sizes:
            lines += [
                f"Temporal split sizes: {sizes}; positives per split: "
                f"{config.get('illicit_in_split', 'n/a')}.",
                "",
            ]
        table = summarise(results)
        latex_tables[folder.name] = table
        lines += [to_md(table), ""]
        lines += ["Mean ± standard deviation over seeds; deterministic models are run once.", ""]
        per_pattern = next(
            (
                f / "per_pattern_recall.csv"
                for f in folders
                if (f / "per_pattern_recall.csv").exists()
            ),
            None,
        )
        if per_pattern is not None:
            frame = pd.read_csv(per_pattern).round(3)
            lines += [
                "### Per-motif recall of the structural-motif scanner (test split)",
                "",
                to_md(frame),
                "",
            ]
        for f in folders:
            env = f / "environment.json"
            if env.exists():
                info = json.loads(env.read_text())
                title = "Environment" if len(folders) == 1 else f"Environment of `{f}`"
                lines += [
                    f"<details><summary>{title}</summary>",
                    "",
                    "```json",
                    json.dumps(info, indent=2),
                    "```",
                    "",
                    "</details>",
                    "",
                ]

    (out_dir / "REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    (out_dir / "results.tex").write_text(to_latex(latex_tables), encoding="utf-8")
    print(f"wrote {out_dir / 'REPORT.md'} and {out_dir / 'results.tex'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
